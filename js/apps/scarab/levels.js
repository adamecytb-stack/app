export const TILES = {
  WALL: '#',
  OPEN: '.',
  COIN: 'o',
  GEM: '*',
  SPIKE: '^',
  EXIT: 'X',
  START: 'S',
  SHIELD: '+',
  WARDEN_H: '~',
  WARDEN_V: '|',
};

export const COLS = 15;

/** Anything the player can pass through. Only walls block a slide. */
export function isSolid(ch) { return ch === TILES.WALL; }

/** Turns ASCII into a world: floor-up grid plus the entities on it. */
export function parseGrid(rows) {
  const flipped = [...rows].reverse();
  const grid = flipped.map((line) => line.split(''));
  const coins = [];
  const gems = [];
  const spikes = [];
  const shields = [];
  const wardens = [];
  let start = { c: 1, r: 1 };
  let exit = null;

  grid.forEach((line, r) => {
    line.forEach((ch, c) => {
      if (ch === TILES.COIN) { coins.push({ c, r }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.GEM) { gems.push({ c, r }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.SPIKE) { spikes.push({ c, r }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.SHIELD) { shields.push({ c, r }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.WARDEN_H) { wardens.push({ c, r, axis: 'h' }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.WARDEN_V) { wardens.push({ c, r, axis: 'v' }); grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.START) { start = { c, r }; grid[r][c] = TILES.OPEN; }
      else if (ch === TILES.EXIT) { exit = { c, r }; grid[r][c] = TILES.OPEN; }
    });
  });

  // Spikes are bolted to a wall and point away from it. Working the facing
  // out from the finished grid means it can never disagree with the map —
  // a spike floating in mid-air with nothing behind it looks broken.
  const isWall = (c, r) => !grid[r] || grid[r][c] === undefined || grid[r][c] === TILES.WALL;
  for (const spike of spikes) {
    const { c, r } = spike;
    if (isWall(c, r - 1)) spike.dir = 'up';
    else if (isWall(c, r + 1)) spike.dir = 'down';
    else if (isWall(c - 1, r)) spike.dir = 'right';
    else if (isWall(c + 1, r)) spike.dir = 'left';
    else spike.dir = null;          // unanchored — the generator rejects these
  }

  return { grid, coins, gems, spikes, shields, wardens, start, exit, rows: grid.length };
}
