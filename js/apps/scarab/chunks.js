/** Chunks legal at a given height, so the climb ramps up as you go. */
export function chunksForHeight(height) {
  const tier = height < 60 ? 0 : height < 160 ? 1 : 2;
  const allowed = CHUNKS.filter((c) => c.tier <= tier);
  // Keep a little easy material in the mix even up high, so it breathes.
  return allowed.length ? allowed : CHUNKS;
}
